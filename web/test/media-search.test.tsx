it('switches scope, ignores late results, and navigates to the result channel',async()=>{
  const pending:Array<{resolve:(value:{items:SearchItem[];total:number})=>void;signal:AbortSignal}>=[];
  const search=vi.fn((_query,_scope,_offset,signal)=>new Promise(resolve=>pending.push({resolve,signal})));
  const navigate=vi.fn();
  await act(async()=>render(<MediaSearch api={{preferenceScope:()=> 'test',search} as unknown as MediaApi} channel="music" navigate={navigate}/>,root));
  expect(search).not.toHaveBeenCalled();
  await act(async()=>{const input=root.querySelector('input')!;input.value='测试';input.dispatchEvent(new Event('input',{bubbles:true}));});
  await act(async()=>{root.querySelector('form')!.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));});
  expect(search.mock.calls[0]!.slice(0,3)).toEqual(['测试','music',0]);
  await act(async()=>{root.querySelector<HTMLButtonElement>('[data-scope=all]')!.click();});
  expect(pending[0]!.signal.aborted).toBe(true);
  const item:SearchItem={id:'film',libraryId:'lib',title:'测试电影',kind:'movie',channel:'video',libraryName:'电影库',parentId:null,metadata:{},overrides:{}};
  await act(async()=>pending[1]!.resolve({items:[item],total:1}));
  await act(async()=>pending[0]!.resolve({items:[],total:0}));
  expect(root.textContent).toContain('测试电影');
  await act(async()=>root.querySelector<HTMLButtonElement>('.media-search-result')!.click());
  expect(navigate).toHaveBeenCalledWith('video','film');
  act(()=>render(null,root));
  expect(pending[1]!.signal.aborted).toBe(true);
});

