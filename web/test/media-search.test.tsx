it.each([false,true])('recovers an invalid search page without a false empty result (failure=%s)',async(failRecovery)=>{
  const item:SearchItem={id:'track',libraryId:'lib',title:'保留的结果',kind:'track',channel:'music',libraryName:'音乐',parentId:null,metadata:{},overrides:{}};
  const search=vi.fn().mockResolvedValueOnce({items:[item],total:61}).mockResolvedValueOnce({items:[],total:1});
  const onLocationChange=vi.fn();
  if(failRecovery)search.mockRejectedValueOnce(new Error('恢复页读取失败'));
  else search.mockResolvedValueOnce({items:[item],total:1});
  await act(async()=>render(<MediaSearch api={{preferenceScope:()=> 'test',search} as unknown as MediaApi} channel="music" onLocationChange={onLocationChange} navigate={()=>{}}/>,root));
  await act(async()=>{const input=root.querySelector('input')!;input.value='保留';input.dispatchEvent(new Event('input',{bubbles:true}));});
  await act(async()=>{root.querySelector('form')!.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));});
  await vi.waitFor(()=>expect(root.querySelector('.media-search-result')).not.toBeNull());
  await act(async()=>[...root.querySelectorAll('button')].find(button=>button.textContent==='下一页')!.click());
  await vi.waitFor(()=>expect(search).toHaveBeenCalledTimes(3));
  expect(search.mock.calls.map(call=>call.slice(0,3))).toEqual([['保留','music',0],['保留','music',60],['保留','music',0]]);
  await vi.waitFor(()=>expect(root.textContent).toContain(failRecovery?'恢复页读取失败':'保留的结果'));
  expect(root.textContent).not.toContain('没有匹配内容');
  expect(root.querySelector('input')!.value).toBe('保留');
  expect(onLocationChange).toHaveBeenLastCalledWith({q:'保留',scope:'music',offset:'0'});
});
